#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOF
    CREATE USER ${AIRFLOW_USER} WITH PASSWORD '${AIRFLOW_PASSWORD}';
    CREATE DATABASE airflow OWNER ${AIRFLOW_USER};
    CREATE DATABASE marquez OWNER ${POSTGRES_USER};
    CREATE DATABASE superset OWNER ${POSTGRES_USER};

    CREATE SCHEMA IF NOT EXISTS raw;
    CREATE SCHEMA IF NOT EXISTS stage;
    CREATE SCHEMA IF NOT EXISTS mart;

    GRANT ALL PRIVILEGES ON SCHEMA raw TO ${POSTGRES_USER};
    GRANT ALL PRIVILEGES ON SCHEMA stage TO ${POSTGRES_USER};
    GRANT ALL PRIVILEGES ON SCHEMA mart TO ${POSTGRES_USER};
EOF
